function normalizeLanguage(value) {
  return value === 'en' ? 'en' : 'de';
}

function translate(language, key, variables = {}) {
  const selected = normalizeLanguage(language);
  const template = TRANSLATIONS[selected][key] ?? TRANSLATIONS.de[key] ?? key;
  return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) => (
    Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : `{${name}}`
  ));
}

module.exports = { TRANSLATIONS, normalizeLanguage, translate };
